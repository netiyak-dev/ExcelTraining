# ---------------------------------------------------------------- helpers
def money(v, dp=2):
    return round(v, dp)

def as_text(v):
    """เก็บตัวเลขเป็นข้อความพร้อมคั่นหลักพัน — กับดักคลาสสิกจากการคัดลอกจากเว็บ/PDF"""
    if isinstance(v, float):
        return "{:,.2f}".format(v)
    return "{:,}".format(v)

def pad(s):
    """เติมช่องว่างนำหน้าหรือตามหลัง — กับดักที่ทำให้ VLOOKUP และ COUNTIF พลาด"""
    return random.choice([" " + str(s), str(s) + " ", "  " + str(s) + " "])

def th_date(d):
    """วันที่แบบ พ.ศ. เป็นข้อความ — Excel ตีความไม่ได้"""
    return "{:02d}/{:02d}/{}".format(d.day, d.month, d.year + 543)

def iso(d):
    return d.isoformat()

def pick(seq):
    return random.choice(seq)

def maybe(p):
    return random.random() < p

def drift(base, pct=0.15):
    return base * (1 + random.uniform(-pct, pct))


